#define GLYPH_BASE 0x20u
#define GLYPH_END  0x5Au

const uint8_t *font5x7_glyph(char c)
{
    const uint8_t uc = (uint8_t)c;
    if (uc < GLYPH_BASE || uc > GLYPH_END)
        return nullptr;
    return glyphs[uc - GLYPH_BASE];
}
